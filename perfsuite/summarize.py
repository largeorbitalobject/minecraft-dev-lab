#!/usr/bin/env python3
"""Orbital Atlas perf suite: medians, spreads, LOD/capacity tables and regression flags from score.py output.

  summarize.py [--data /root/atlas-beta-program/perf-dossier/data] [--md /root/atlas-beta-program/perf-dossier/summary.md]
               [--builds 0.2.0-beta.1-rc.142,0.2.0-beta.1-rc.159,0.2.0-beta.1-rc.160]

Only PASS runs count. Each host is compared only with itself; ct224 rows are listed as correctness-only.
Per run, pooled groups (join_*, fly_*, walk_*) take the median over their windows first; then each cell = median [min-max] nN
over runs. Regression flag (dossier rule): build B is >10% worse than build A on frame p50 or p95 (or Atlas CPU p95 / tile latency
p95) in EVERY B run (needs >= 2 B runs): min(B) > 1.10 x median(A).
"""
import argparse, collections, json, os, re, statistics

GROUPS = [
    ("join (0-30 s after world load)", r"^join_"), ("world map 64 cold", r"^wm1_still_64$"), ("world map 128 cold", r"^wm1_still_128$"),
    ("world map 256 cold", r"^wm1_still_256$"), ("world map 512 cold", r"^wm1_still_512$"), ("world map 1024 cold", r"^wm1_still_1024$"),
    ("world map 64 warm", r"^wm2_still_64$"), ("world map 256 warm", r"^wm2_still_256$"), ("world map 1024 warm", r"^wm2_still_1024$"),
    ("pan 64", r"^wm1_pan_64$"), ("pan 256", r"^wm1_pan_256$"), ("pan 1024", r"^wm1_pan_1024$"), ("spin 256", r"^wm_spin_256$"),
    ("flight 30 b/s (6x10 s)", r"^fly_"), ("after landing 20-30 s", r"^land_20_30s$"), ("walk 5 min (10x30 s)", r"^walk_"),
    ("close zoom 64 relief", r"^close64_still$"), ("revisit HUD 15-25 s", r"^revisit_15_25s$"), ("revisit world map 256", r"^revisit_wm_256$"),
    ("cave minimap 64", r"^mm_cave_64$"), ("cave minimap 128", r"^mm_cave_128$"), ("cave minimap 256", r"^mm_cave_256$"),
    ("cave world map 64", r"^wm_cave_64$"), ("cave world map 128", r"^wm_cave_128$"), ("cave world map 256", r"^wm_cave_256$"),
    ("cave world map 640", r"^wm_cave_640$"), ("cave world map 1024", r"^wm_cave_1024$"), ("cave pan 1024", r"^wm_cave_pan_1024$"),
    ("cave spin 128", r"^wm_cave_spin_128$"),
]
METRICS = [("frame p50 ms", "frame_ms_p50"), ("frame p95 ms", "frame_ms_p95"), ("frame p99 ms", "frame_ms_p99"), ("hitches>=50ms per window", "hitches_50ms"),
           ("Atlas render-thread CPU per frame p50 ms (all frames)", "oa.map_cpu_p50_ms"),
           ("Atlas render-thread CPU per frame p95 ms (all frames)", "oa.map_cpu_p95_ms"),
           ("GC pause ms per window", "gc_pause_ms_total"), ("tile in view p95 ms (censored)", "oa.tile_view_cens_ms_p95")]
EXTRA_ARMS_ONLY_SUMMARY = True
FLAG_METRICS = ("frame_ms_p50", "frame_ms_p95", "oa.map_cpu_p50_ms", "oa.map_cpu_p95_ms", "oa.tile_view_cens_ms_p95")


def short(b):
    return (b or "?").replace("0.2.0-beta.1-", "")


def cell(vals):
    v = [x for x in vals if x is not None]
    if not v:
        return "-"
    med = statistics.median(v)
    if len(v) == 1:
        return "%s n1" % fmt(med)
    return "%s [%s-%s] n%d" % (fmt(med), fmt(min(v)), fmt(max(v)), len(v))


def fmt(x):
    if x is None:
        return "-"
    return ("%.0f" % x) if abs(x) >= 100 else ("%.1f" % x) if abs(x) >= 10 else ("%.2f" % x)


def load(path):
    return [json.loads(l) for l in open(path)] if os.path.isfile(path) else []


def timing_run_eligible(row):
    return row.get("verdict") in ("PASS", "WARN_SLOW_EXIT") and row.get("timing_comparison_eligible", True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="/root/atlas-beta-program/perf-dossier/data")
    ap.add_argument("--md", default="/root/atlas-beta-program/perf-dossier/summary.md")
    ap.add_argument("--builds", default="0.2.0-beta.1-rc.142,0.2.0-beta.1-rc.159,0.2.0-beta.1-rc.160,perfsuite-census1")
    a = ap.parse_args()
    runs = {r["run_id"]: r for r in load(os.path.join(a.data, "runs.jsonl"))}
    segs = load(os.path.join(a.data, "segments.jsonl"))
    order = a.builds.split(",")
    ok = {k for k, r in runs.items() if timing_run_eligible(r)}
    # per run, per group: pooled metric value
    per = collections.defaultdict(lambda: collections.defaultdict(list))   # (run, group) -> metric -> [vals over windows]
    for s in segs:
        if s["run_id"] not in ok:
            continue
        for gname, rx in GROUPS:
            if re.search(rx, s["segment"] or ""):
                for _, mk in METRICS:
                    v = s["metrics"].get(mk)
                    if v is not None:
                        per[(s["run_id"], gname)][mk].append(v)
    pooled = {k: {mk: statistics.median(v) for mk, v in d.items()} for k, d in per.items()}
    out = ["# Orbital Atlas perf suite: summary", "",
           "Generated by perfsuite/summarize.py from data/*.jsonl. Cells: median [min-max] nRuns over PASS and validated WARN_SLOW_EXIT runs; pooled groups take the per-run",
           "median over their windows first. Each host is compared only with itself. Arm `base` = default settings + diag + mapPerfLog;",
           "`cap120` = sceneMeshBudgetMb=120 non-adaptive. ct224 is correctness-only (shared host, never compare its timings).", ""]
    # run inventory
    inv = collections.Counter((r["host"], r["scenario"], short(r["build"]), r["arm"], r["verdict"]) for r in runs.values())
    out += ["## Run inventory", "", "| host | scenario | build | arm | verdict | runs |", "|---|---|---|---|---|---|"]
    for k in sorted(inv):
        out.append("| %s | %s | %s | %s | %s | %d |" % (k + (inv[k],)))
    out.append("")
    ineligible = [r for r in runs.values() if r.get("timing_comparison_eligible") is False]
    if ineligible:
        out += ["## Timing comparisons excluded by realism audit", "",
                "Harness verdicts below still describe step/screenshot execution. An entire run is excluded from timing comparisons",
                "when any recognized detail station is contaminated or unmeasured; legacy runs without detail stations remain eligible.", "",
                "| host | run | harness verdict | reason |", "|---|---|---|---|"]
        for r in sorted(ineligible, key=lambda r: r["run_id"]):
            out.append("| %s | %s | %s | %s |" % (r["host"], r["run_id"], r["harness_verdict"], r.get("timing_exclusion_reason") or "Unmeasured detail realism"))
        out.append("")
    texture_runs = [r for r in runs.values() if r["scenario"] == "q-texture"]
    if texture_runs:
        out += ["## Plain-surface close zoom: time to first textured tile", "",
                "`map_state` drawn count = lastMap detT+detS plus lastRegional detT+detS. Time starts at open_map.",
                "Zero textures in 60 s, late first texture, missing telemetry/product profile, inconsistent fixtures, or unrepresentative recapture fail the scorecard.",
                "CT224 establishes correctness only. First observation is an upper bound at the polling resolution.", "",
                "| host | build | fixture | first texture ms | max textured tiles | observed ms | scorecard | reason |",
                "|---|---|---|---|---|---|---|---|"]
        for r in sorted(texture_runs, key=lambda r: (r["host"], r["run_id"])):
            t = r["derived"]["texture"]
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s |" %
                       (r["host"], short(r["build"]), t["fixture"], fmt(t["first_textured_ms"]),
                        fmt(t["max_textured_tiles"]), fmt(t["observed_ms"]), t["verdict"],
                        "; ".join(t["reasons"] + t["notes"]) or "-"))
        out.append("")
    slow = [r for r in runs.values() if r["verdict"] == "WARN_SLOW_EXIT"]
    if slow:
        out += ["## Slow exit warnings", "", "These measurements passed all steps and frame validation, and Java exit was confirmed. World-save evidence is retained separately; an unsaved exit is not a saved PASS.", ""]
        for r in sorted(slow, key=lambda r: r["run_id"]):
            out.append("- %s %s: WARN_SLOW_EXIT; harness=%s; saved=%s; graceful=%s. %s" % (r["host"], r["run_id"], r.get("harness_verdict"), r.get("exit_saved"), r.get("exit_graceful"), r.get("exit_warning") or r.get("reason") or ""))
        out.append("")
    flags = []
    hosts = [h for h in ("fd", "gpc", "mac", "ct224") if any(r["host"] == h for r in runs.values())]
    for host in hosts:
        for scen in sorted({r["scenario"] for r in runs.values() if r["host"] == host}):
            for arm in sorted({r["arm"] for r in runs.values() if r["host"] == host and r["scenario"] == scen}):
                if not scen.startswith("q-") or ("@" in arm or "+jfr" in arm or arm != "base"):
                    continue   # fps-capped / JFR / non-base arms: see the arm comparison section
                rs = [r for r in runs.values() if r["host"] == host and r["scenario"] == scen and r["arm"] == arm and r["run_id"] in ok]
                if not rs:
                    continue
                bl = [b for b in order if any(r["build"] == b for r in rs)] + sorted({r["build"] for r in rs} - set(order))
                out += ["## %s / %s / arm %s%s" % (host, scen, arm, " (CORRECTNESS ONLY, not perf-comparable)" if host == "ct224" else ""), ""]
                for mname, mk in METRICS:
                    rowsm = []
                    for gname, _ in GROUPS:
                        vals = {b: [pooled.get((r["run_id"], gname), {}).get(mk) for r in rs if r["build"] == b] for b in bl}
                        if not any(x is not None for v in vals.values() for x in v):
                            continue
                        rowsm.append("| %s | %s |" % (gname, " | ".join(cell(vals[b]) for b in bl)))
                        if mk in FLAG_METRICS and host != "ct224":
                            for i, bb in enumerate(bl):
                                for aa in bl[:i]:
                                    B = [x for x in vals[bb] if x is not None]; A = [x for x in vals[aa] if x is not None]
                                    floor = 500.0 if "tile" in mk else 0.5   # absolute floor: ignore sub-0.5 ms (or sub-0.5 s latency) moves
                                    if len(B) >= 2 and A and min(B) > 1.10 * statistics.median(A) and min(B) - statistics.median(A) >= floor:
                                        flags.append((host, scen, arm, gname, mk, short(aa), short(bb), statistics.median(A), B))
                    if rowsm:
                        out += ["**%s**" % mname, "", "| segment | " + " | ".join(short(b) for b in bl) + " |", "|---|" + "---|" * len(bl)] + rowsm + [""]
    # Arm comparison (rc.160 and the census build): base vs Atlas-off vs budget arms, per host, q-basepack main groups
    AG = ["join (0-30 s after world load)", "world map 256 cold", "world map 1024 cold", "flight 30 b/s (6x10 s)", "after landing 20-30 s",
          "walk 5 min (10x30 s)", "revisit HUD 15-25 s"]
    AM = [("fps", "fps_avg"), ("frame p50", "frame_ms_p50"), ("frame p95", "frame_ms_p95"), ("Atlas CPU p95", "oa.map_cpu_p95_ms"),
          ("hitches", "hitches_50ms"), ("GC ms", "gc_pause_ms_total"), ("heap max MB", "heap_used_mb_max")]
    out += ["## Arm comparison on q-basepack (each host with itself)", "",
            "`off` = Atlas off for the whole session (orbitalatlas.harnessMapOff=true, same route); `cap120` = 120 MB mesh budget pinned;",
            "`b400` = 400 MB pinned (fd only; fd's adaptive default is 120); `diagx` = census build + scopeDiagnostics, with JFR (not a timing arm);",
            "`@fps60` = 60 fps cap (first runs only). Cells: median [min-max] nRuns.", ""]
    for host in hosts:
        if host == "ct224":
            continue
        rs_h = [r for r in runs.values() if r["host"] == host and r["scenario"] == "q-basepack" and r["run_id"] in ok]
        combos = sorted({(r["build"], r["arm"]) for r in rs_h}, key=lambda x: (order.index(x[0]) if x[0] in order else 99, x[1]))
        if not combos:
            continue
        out += ["### %s" % host, "", "| segment | metric | " + " | ".join("%s %s" % (short(b), a) for b, a in combos) + " |", "|---|---|" + "---|" * len(combos)]
        for gname in AG:
            for mname, mk in AM:
                vals = [cell([pooled.get((r["run_id"], gname), {}).get(mk) for r in rs_h if r["build"] == b and r["arm"] == a]) for b, a in combos]
                if any(v != "-" for v in vals):
                    out.append("| %s | %s | %s |" % (gname, mname, " | ".join(vals)))
        out.append("")
    # Nightly / other scenarios: every segment raw (first PASS run per host/build/arm)
    for host in hosts:
        for scen in sorted({r["scenario"] for r in runs.values() if r["host"] == host and r["scenario"].startswith("n-")}):
            for r in sorted([r for r in runs.values() if r["host"] == host and r["scenario"] == scen], key=lambda r: r["run_id"]):
                status = r["verdict"] + ("; TIMING INELIGIBLE" if r.get("timing_comparison_eligible") is False else "")
                out += ["## %s / %s / %s / %s (%s)%s" % (host, scen, short(r["build"]), r["arm"], status, " CORRECTNESS ONLY" if host == "ct224" else ""), "",
                        "| segment | fps | frame p50 | frame p95 | frame p99 | hitches | Atlas CPU p95 | GC ms | heap max MB | tick p95 |", "|---|---|---|---|---|---|---|---|---|---|"]
                for sg in [x for x in segs if x["run_id"] == r["run_id"]]:
                    m = sg["metrics"]
                    out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (sg["segment"], fmt(m.get("fps_avg")), fmt(m.get("frame_ms_p50")), fmt(m.get("frame_ms_p95")),
                               fmt(m.get("frame_ms_p99")), fmt(m.get("hitches_50ms")), fmt(m.get("oa.map_cpu_p95_ms")), fmt(m.get("gc_pause_ms_total")),
                               fmt(m.get("heap_used_mb_max")), fmt(m.get("tick_ms_p95"))))
                out.append("")
    # scope split (diagx arm)
    SC = ["deferred", "hud", "screen", "tick", "chunk", "block", "reload", "other"]
    dx = [r for r in runs.values() if r["arm"].startswith("diagx") and r["run_id"] in ok]
    if dx:
        out += ["## Atlas render-thread CPU by scope (arm diagx: census build + scopeDiagnostics, JFR attached)", "",
                "Per-frame Atlas work split by MapMetrics scope (p95 ms per window, per-run median over the group's windows). JFR adds",
                "overhead, so use these for the split, not for absolute timing.", ""]
        out += ["| host | scenario | segment | total p95 | " + " | ".join(SC) + " |", "|---|---|---|---|" + "---|" * len(SC)]
        for r in sorted(dx, key=lambda r: (r["host"], r["scenario"])):
            for gname, rx in GROUPS:
                ws = [x["metrics"] for x in segs if x["run_id"] == r["run_id"] and re.search(rx, x["segment"] or "")]
                if not ws:
                    continue
                med = lambda k: fmt(statistics.median([w[k] for w in ws if w.get(k) is not None])) if any(w.get(k) is not None for w in ws) else "-"
                out.append("| %s | %s | %s | %s | %s |" % (r["host"], r["scenario"], gname, med("oa.map_cpu_p95_ms"),
                           " | ".join(med("oa.scope_%s_cpu_p95_ms" % k) for k in SC)))
        out.append("")
    # LOD timing / mix
    out += ["## LOD timing and mix", "",
            "Minimap LOD mix while flying (30 b/s): `miniLevels` census after each 10 s flight window (regional minimap only; the",
            "ordinary walking minimap draws local tiles and has no level census, so landing/revisit sharpness is given as fine-tile",
            "coverage and tile latency of the window instead). Shares are of explored chunk cells in the HUD disc, not pixels.", "",
            "| host | build | arm | fly l0 (fine) | fly l1-l2 (medium) | fly l3+ (coarse) | fly blank | land 20-30 s coverage % | land tile p95 ms | revisit 15-25 s coverage % | revisit first-paint p95 ms | map_ready_ms (wait_ready after the join windows) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for host in hosts:
        for b in order:
            for arm in ("base", "off", "cap120", "b400", "diagx+jfr"):
                rs = [r for r in runs.values() if r["host"] == host and r["build"] == b and r["arm"] == arm and r["scenario"] == "q-basepack" and r["run_id"] in ok]
                if not rs:
                    continue
                g = lambda k: cell([r["derived"].get(k) for r in rs])
                sg = lambda seg, mk: cell([next((x["metrics"].get(mk) for x in segs if x["run_id"] == r["run_id"] and x["segment"] == seg), None) for r in rs])
                out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (host, short(b), arm, g("fly_mm_l0_share_med"), g("fly_mm_mid_share_med"),
                           g("fly_mm_coarse_share_med"), g("fly_mm_blank_share_med"), sg("land_20_30s", "oa.coverage_pct"), sg("land_20_30s", "oa.tile_view_cens_ms_p95"),
                           sg("revisit_15_25s", "oa.coverage_pct"), sg("revisit_15_25s", "oa.first_paint_view_cens_ms_p95"), sg("land_20_30s", "oa.map_ready_ms")))
    out += ["", "World map per open (q-basepack: wm1 = first open after join (cold), wm2 = second sweep (warm); q-cave: tunnel). Values at",
            "the map_state polls 0 / 0.5 / 1 / 2 / 3 / 5 s after open_map. `coarse/view` = lastRegional coarse tiles / view tiles (all builds);",
            "`l0 share` and `blank share` = wmLevels census (census build only).", ""]
    out += ["| host | build | arm | scen | open# | span | coarse/view tiles over time | wm l0 share over time | wm blank share over time | wmLevelsT (ms) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for host in hosts:
        for b in order:
            for r in sorted([r for r in runs.values() if r["host"] == host and r["build"] == b and r["run_id"] in ok and r["scenario"] in ("q-basepack", "q-cave")], key=lambda r: r["run_id"])[:1]:
                for i, o in enumerate(r["derived"].get("wm_opens", [])[:20]):
                    cv = ["%s/%s" % (fmt(c), fmt(v)) for c, v in zip(o.get("regional_coarse_tiles", []), o.get("regional_view_tiles", []))]
                    l0 = " ".join(fmt(x) for x in o.get("wm_l0_share", [])) or "-"
                    bk = " ".join(fmt(x) for x in o.get("wm_blank_share", [])) or "-"
                    T = o.get("wm_T") or {}
                    out.append("| %s | %s | %s | %s | %d | %s | %s | %s | %s | %s |" % (host, short(b), r["arm"], r["scenario"], i + 1, o["span"], " ".join(cv), l0, bk,
                               " ".join("%s=%s" % (k, fmt(v)) for k, v in T.items()) or "-"))
    # capacity
    out += ["", "## Capacity (mapPerf budget / budgetLevels over the q-basepack run)", "",
            "local = own fine (level-0 local) tiles. bytes/tile from the first window with far-local evictions. Limit = mesh budget",
            "applied to GPU and CPU each.", "",
            "| host | build | arm | budget limit MB | gpu MB max | cpu MB max | local tiles max | local CPU MB max | local GPU MB max | local tiles at 1st far eviction | CPU B/tile | GPU B/tile | far-local evictions (end) | evictions (end) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for host in hosts:
        for b in order:
            for arm in ("base", "off", "cap120", "b400", "diagx+jfr"):
                rs = [r for r in runs.values() if r["host"] == host and r["build"] == b and r["arm"] == arm and r["scenario"] == "q-basepack" and r["run_id"] in ok]
                if not rs:
                    continue
                c = lambda k: cell([(r["derived"].get("capacity") or {}).get(k) for r in rs])
                out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (host, short(b), arm, c("budget_limit_mb"), c("budget_gpu_mb_max"),
                           c("budget_cpu_mb_max"), c("local_n_max"), c("local_cpu_mb_max"), c("local_gpu_mb_max"), c("local_n_at_first_far_eviction"),
                           c("local_bytes_per_tile_cpu"), c("local_bytes_per_tile_gpu"), c("farLocalEvictions_last"), c("budget_evictions_last")))
    # zoom smoothness
    out += ["", "## Zoom smoothness (q-basepack zoom burst: 32 instant span changes 0.25 s apart, 1024<->64)", "",
            "From progress.jsonl (1 Hz samples of the harness frame recorder) inside the burst window.", "",
            "| host | build | arm | burst s | frame max ms | median 1 s frame p95 ms | median fps |", "|---|---|---|---|---|---|---|"]
    for host in hosts:
        for b in order:
            for arm in ("base", "cap120"):
                rs = [r for r in runs.values() if r["host"] == host and r["build"] == b and r["arm"] == arm and r["scenario"] == "q-basepack" and r["run_id"] in ok]
                if rs:
                    g = lambda k: cell([r["derived"].get(k) for r in rs])
                    out.append("| %s | %s | %s | %s | %s | %s | %s |" % (host, short(b), arm, g("zoom_burst_s"), g("zoom_burst_frame_max_ms"), g("zoom_burst_frame_p95_med_ms"), g("zoom_burst_fps_med")))
    # flags
    out += ["", "## Regression flags (>10% worse in every run of the newer build vs the older build's median, and by at least 0.5 ms / 0.5 s)", "",
            "A flag is a candidate, not a verdict: check the confounds (chunk arrivals, server ticks, run order/thermal, feature changes",
            "between the builds) in the run rows before calling it real. rc.142 -> rc.159 includes the cave-styles / storey / cave-window work.", ""]
    if not flags:
        out.append("None.")
    else:
        out += ["| host | scenario | arm | segment | metric | older | newer | older median | newer runs |", "|---|---|---|---|---|---|---|---|---|"]
        for f in flags:
            out.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (f[0], f[1], f[2], f[3], f[4], f[5], f[6], fmt(f[7]), ", ".join(fmt(x) for x in f[8])))
    out += ["", "Failed / unconfirmed runs (excluded from comparisons):", ""]
    for r in sorted(runs.values(), key=lambda r: r["run_id"]):
        if r["verdict"] not in ("PASS", "WARN_SLOW_EXIT"):
            out.append("- %s %s %s: %s %s" % (r["host"], r["run_id"], short(r["build"]), r["verdict"], (r.get("reason") or "")[:200]))
    # profiles index -> table (also written as profiles/SUMMARY.md)
    pidx = os.path.join(os.path.dirname(a.data.rstrip("/")), "profiles", "index.jsonl")
    if os.path.isfile(pidx):
        rows = {}
        for l in open(pidx):
            try:
                r = json.loads(l); rows[r["run_id"]] = r
            except Exception:
                pass
        pt = ["## JFR profiles (profiles/*.txt; JFR settings=profile, window = first measure -> end of run)", "",
              "| host | scenario | build | render-thread Java samples | with Atlas frame | render native samples | Atlas threads (samples) | alloc total GB | alloc under Atlas | GC pause ms (n, Full) | file |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(rows.values(), key=lambda r: (r["host"], r["run_id"])):
            at = ", ".join("%s %d" % (k.replace("Orbital Atlas ", "").replace("OrbitalAtlas ", ""), v) for k, v in sorted(r.get("atlas_threads", {}).items(), key=lambda x: -x[1])[:4])
            pt.append("| %s | %s | %s | %s | %s%% | %s | %s | %s | %s%% | %s (%s, %s) | %s |" % (r["host"], r["scenario"], r["build"], r.get("render_samples"),
                      r.get("render_atlas_pct"), r.get("render_native_samples", "-"), at, r.get("alloc_total_gb", "-"), r.get("alloc_atlas_pct", "-"),
                      r.get("gc_pause_ms", "-"), r.get("gc_n", "-"), r.get("gc_full_n", "-"), r["file"]))
            for ph, v in (r.get("phases") or {}).items():
                pt.append("|  | phase: %s |  | %s | %s%% |  |  |  |  |  |  |" % (ph, v.get("render_samples"), v.get("render_atlas_pct")))
        out += [""] + pt
        open(os.path.join(os.path.dirname(pidx), "SUMMARY.md"), "w").write("# JFR profile index\n\nGenerated by perfsuite/summarize.py from profiles/index.jsonl.\n"
            "Hand-attached JFRs (rc.159 fd/GPC, `JFR_ATTACHED.txt` in the archive) cover only the last 31 s (fd) / ~3.5 min (GPC) of their run.\n\n" + "\n".join(pt) + "\n")
    open(a.md, "w").write("\n".join(out) + "\n")
    json.dump([dict(zip(("host", "scenario", "arm", "segment", "metric", "older", "newer", "older_median", "newer_runs"), f)) for f in flags],
              open(os.path.join(a.data, "flags.json"), "w"), indent=1)
    print("wrote", a.md, "flags", len(flags))


